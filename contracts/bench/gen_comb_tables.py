#!/usr/bin/env python3
"""Generate contracts/bench/PallasCombTables.sol (BENCHMARK ONLY).

For each comb width t in 4..8, spacing d = ceil(255 / t), entry idx in
[1, 2^t) is the affine point  sum_{i : bit i of idx} 2^(d*i) * G  on Pallas,
G being the RedPallas SpendAuth base used by contracts/src/Pallas.sol.
Each table is the runtime code of a data contract: one 0x00 (STOP) byte, then
64-byte entries (x, y big-endian) in idx order. Before writing, the script runs
the same comb with the same bit-gather constants in Python against plain
double-and-add for edge and random scalars, and fails on any mismatch.
"""
import random
import subprocess
from pathlib import Path

P = 0x40000000000000000000000000000000224698fc094cf91b992d30ed00000001
Q = 0x40000000000000000000000000000000224698fc0994a8dd8c46eb2100000001
G = (0x375523b328f1d6063b8d187c3e5f445f0c7f0ce37b70a10c8d1a7284b875c963,
     0x1ad0357fdf1a66db7b10bcfcfed624fbdfc914fec005bdd84ce33e817b0c3bc9)
TEETH = range(4, 9)
OUT = Path(__file__).resolve().with_name('PallasCombTables.sol')


def add(a, b):
    if a is None: return b
    if b is None: return a
    if a[0] == b[0] and (a[1] + b[1]) % P == 0: return None
    if a == b:
        m = 3 * a[0] * a[0] * pow(2 * a[1], -1, P) % P
    else:
        m = (b[1] - a[1]) * pow(b[0] - a[0], -1, P) % P
    x = (m * m - a[0] - b[0]) % P
    return (x, (m * (a[0] - x) - a[1]) % P)


def mul(k, point=G):
    r = None
    for bit in bin(k)[2:]:
        r = add(r, r)
        if bit == '1': r = add(r, point)
    return r


def params(t):
    """Spacing, gather mask, gather multiplier and shift for t teeth."""
    d = -(-255 // t)
    base = (d - 1) * (t - 1)
    assert t < d and (t - 1) * d < 256 and base + t <= 256
    mask = sum(1 << (d * i) for i in range(t))
    magic = sum(1 << (base - (d - 1) * i) for i in range(t))
    return d, mask, magic, base


def table(t):
    d = params(t)[0]
    bases = [mul(1 << (d * i)) for i in range(t)]
    out = [None]
    for idx in range(1, 1 << t):
        point = None
        for i in range(t):
            if idx >> i & 1: point = add(point, bases[i])
        assert point is not None and point[0] < P and point[1] < P
        assert (point[1] ** 2 - point[0] ** 3 - 5) % P == 0
        out.append(point)
    return out


def comb(k, t, entries):
    d, mask, magic, base = params(t)
    r = None
    for j in reversed(range(d)):
        r = add(r, r)
        idx = (((k >> j) & mask) * magic % 2**256 >> base) & ((1 << t) - 1)
        expect = sum(((k >> (j + d * i)) & 1) << i for i in range(t))
        assert idx == expect, (k, t, j)
        if idx: r = add(r, entries[idx])
    return r


def code(entries):
    return b'\x00' + b''.join(x.to_bytes(32, 'big') + y.to_bytes(32, 'big') for x, y in entries[1:])


def keccak(data):
    return subprocess.run(['cast', 'keccak', '0x' + data.hex()], capture_output=True, text=True,
                          check=True).stdout.strip()


def main():
    rng = random.Random(20261018)
    scalars = [1, 2, 3, Q - 1, Q - 2, 2**254 - 1, 2**254, 2**253 + 1]
    scalars += [rng.randrange(1, Q) for _ in range(24)]
    parts = ['// SPDX-License-Identifier: MIT', 'pragma solidity 0.8.25;', '',
             '// GENERATED by contracts/bench/gen_comb_tables.py. BENCHMARK ONLY, not deployed.',
             '// Each constructor returns its table as runtime code: 0x00, then 64-byte',
             '// affine entries (x, y) for idx = 1 .. 2^t - 1, entry = sum 2^(d*i) G over bits i of idx.',
             '']
    hashes = []
    for t in TEETH:
        entries = table(t)
        for k in scalars:
            assert comb(k, t, entries) == mul(k), (t, k)
        data = code(entries)
        assert len(data) <= 24576
        hashes.append((t, keccak(data), len(data)))
        parts += [f'contract PallasCombTable{t} {{', '    constructor() {',
                  f'        bytes memory table = hex"{data.hex()}";',
                  '        assembly { return(add(table, 0x20), mload(table)) }', '    }', '}', '']
    parts.append('library PallasCombTables {')
    for t, digest, size in hashes:
        parts.append(f'    uint256 internal constant SIZE_{t} = {size};')
        parts.append(f'    bytes32 internal constant CODEHASH_{t} = {digest};')
    parts += ['', '    /// Code hash of PallasCombTable{t}; zero for an unsupported width.',
              '    function codehash(uint256 t) internal pure returns (bytes32) {']
    for t, digest, size in hashes:
        parts.append(f'        if (t == {t}) return CODEHASH_{t};')
    parts += ['        return bytes32(0);', '    }', '}', '']
    OUT.write_text('\n'.join(parts))
    for t, digest, size in hashes:
        print(f't={t} d={params(t)[0]} bytes={size} codehash={digest}')


if __name__ == '__main__':
    main()
